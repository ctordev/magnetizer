// ── Узел управления тиристором (запуск VT1): общий для основной установки (magnetizer.html, US1)
// и упрощённой (magnetizer-simple.html, US2). Конденсаторный разряд по кнопке «Пуск» — дешёвый
// и стандартный для импульсных установок способ: C2 заряжается от шины «+» через R4, SA2 бросает
// его в затвор через R3; VD7 не пускает обратное напряжение на затвор (у тиристоров обратное
// Uз-к всего 10 В), VD8 ограничивает Uз-к сверху, R5 (Rг-к 22 Ом) держит затвор при dv/dt —
// требование §5 основной установки. Числа: ток в затвор, длительность, мощность на R3, заряд C2.
// Запускать: node calc/src/gate.js   (таблица для обеих установок)

const GATE = {
  C: 1e-6,          // C2 — накопительный конденсатор импульса, 1 мкФ/400 В (керамика/плёнка)
  R3: 100,          // R3 — импульсный резистор (Р3-25, ОИМ-2, 2 Вт): ток и крутизна фронта
  R4: 220e3,        // R4 — заряд C2 от шины «+»: τ = 0,22 с, на нём <0,5 Вт → 1 Вт
  Vz: 12,           // VD8 — стабилитрон 12 В между затвором и катодом (BZX55C12, Д814Д)
  Vd: 1,            // VD7 — последовательный диод (1N4007, КД226): падение, защита от обратной полярности
  Rgk: 22,          // R5 — Rг-к 22 Ом затвор-катод (§5 основной: 22–30 Ом)
};

// U — напряжение шины, на которой стоит C2 (300 В в основной, пик сети в упрощённой).
function gate(U, g = GATE) {
  const iTot = (U - g.Vz - g.Vd) / g.R3;        // ток из C2 в момент пуска (затвор открыт, Uз-к ≈ Vz)
  const iRgk = g.Vz / g.Rgk;                    // часть тока уходит в R5 (он под Vz)
  return {
    U, iTot, iGate: iTot - iRgk,                // что реально течёт в затвор
    tau: g.R3 * g.C,                            // длительность импульса ≈ 100 мкс
    e: 0.5 * g.C * U * U,                       // энергия импульса, Дж
    pR3: iTot * iTot * g.R3,                    // пиковая мощность на R3, Вт (импульсная, ~100 мкс)
    t95: 3 * g.R4 * g.C,                        // заряд C2 до 95 % после включения QF1
    pR4: U * U / g.R4,                          // на R4 в выдержанном режиме, Вт
  };
}

const f = (x, n = 2) => x.toFixed(n).replace('.', ',');

if (require.main === module) {
  console.log('узел управления тиристором: C2 ' + f(GATE.C * 1e6, 0) + ' мкФ, R3 ' + GATE.R3 + ' Ом, R4 ' +
    f(GATE.R4 / 1e3, 0) + ' кОм, VD8 ' + GATE.Vz + ' В, R5 ' + GATE.Rgk + ' Ом');
  console.log('U шины → ток в затвор / всего из C2 / τ импульса / энергия / пик. Вт на R3 / заряд C2 95 % / Вт на R4');
  for (const [name, U] of [['основная 255 В (режим «255») — Т253', 300], ['основная 127 В (режим «127») — Т253', 127],
    ['упрощённая A: пик сети 230 В — Т160', 325], ['упрощённая A: пик сети 253 В — Т160', 358],
    ['упрощённая B: 150 В — Т160', 150]]) {
    const g = gate(U);
    console.log(`  ${name}: ${f(g.iGate)} А в затвор (из C2 ${f(g.iTot)} А), τ=${f(g.tau * 1e6, 0)} мкс, ` +
      `${f(g.e * 1e3, 0)} мДж, на R3 ${f(g.pR3, 0)} Вт (импульс), C2 готов за ${f(g.t95, 1)} с, на R4 ${f(g.pR4, 2)} Вт`);
  }
  console.log('  порог: Iу.от 0,2 А (Т160 и Т253, 25 °C), минимально допустимый импульс затвора Т160 — 0,5 А;');
  console.log('  во всех режимах ток в затвор ≥0,5 А и ≥3× Iу.от; фронт ≤1 мкс — витая пара затвора ≤100 мм.');
}

module.exports = { GATE, gate };
