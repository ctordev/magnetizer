// ── самопроверка геометрии: ни одна деталь ярма не должна попадать в тело обмотки ──
// обмотка 2 слоя × 12: bore r = 50, наружный радиус по жиле 64, |z| ≤ 42 (78 мм намотки + полувиток)
function checkWindingClearance() {
  const skip = new Set([WIRE.coil, '#b06a2c', '#9c5f26', WIRE.magnet, WIRE.ferrite, '#41a6ff', '#1d2f45',
    '#3a4250', '#ff6b6b', '#5b5f66', '#7d8794']);
  const problems = [];
  for (const m of MODELS) for (const [i, part] of m.parts.entries()) {
    if (skip.has(part.m)) continue;
    let rMin = Infinity, zMax = 0;
    for (let k = 0; k < part.g.pts.length; k += 3) {
      const r = Math.hypot(part.g.pts[k], part.g.pts[k + 1]), z = Math.abs(part.g.pts[k + 2]);
      if (r > 49 && r < 65 && z < 43) { rMin = Math.min(rMin, r); zMax = Math.max(zMax, z); }
    }
    if (rMin < Infinity)
      problems.push(`${m.id} #${i} ${part.lbl || part.tx || '(без подписи)'}: вершина в r=${rMin.toFixed(1)}, z=${zMax.toFixed(1)}`);
  }
  if (problems.length) console.warn('⚠ деталь попадает в объём обмотки:\n  ' + problems.join('\n  '));
  else console.log('✓ объём обмотки (r 50…64, |z|<43) свободен во всех моделях');
}
