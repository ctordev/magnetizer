const PI2 = Math.PI * 2;

// ── геометрия (всё в мм, ось Z — ось катушки, полюс ярма ⊥ Z) ───────────────
function cyl(rc, h, seg = 14, c1 = 0, c2 = 1, axis = 'z') {
  const p = [], b = [];
  for (let i = 0; i < seg; i++) {
    const a1 = PI2 * i / seg, a2 = PI2 * (i + 1) / seg;
    const q = (a, z) => axis === 'z' ? [rc * Math.cos(a), rc * Math.sin(a), z] : [z, rc * Math.cos(a), rc * Math.sin(a)];
    if (c1) p.push(q(a1, -h / 2), q(a2, -h / 2), q(a2, h / 2), q(a1, h / 2));
    if (c2) p.push(q(a1, h / 2), q(a2, h / 2), q(a2, -h / 2), q(a1, -h / 2));
  }
  for (let i = 0; i < p.length; i += 4) b.push([i, i + 1, i + 2, i + 3]);
  return mv({ pts: p.flat(), faces: b });
}
function torus(R, r, nu = 12, nv = 8, rot = 0) {
  const p = [], b = [];
  for (let i = 0; i <= nu; i++) for (let j = 0; j <= nv; j++) {
    const u = PI2 * i / nu, v = PI2 * j / nv;
    const x = (R + r * Math.cos(v)) * Math.cos(u), y = (R + r * Math.cos(v)) * Math.sin(u), z = r * Math.sin(v);
    p.push([x, y * Math.cos(rot) - z * Math.sin(rot), y * Math.sin(rot) + z * Math.cos(rot)]);
  }
  for (let i = 0; i < nu; i++) for (let j = 0; j < nv; j++) {
    const k = i * (nv + 1) + j;
    b.push([k, k + nv + 1, k + nv + 2, k + 1]);
  }
  return { pts: p.flat(), faces: b };
}
// обмотка: непрерывная спираль прямоугольной шины (дешевле и читается лучше, чем N отдельных торов)
function helix(R, pitch, n, w, h, nu = 9) {
  const pts = [], faces = [], N = n * nu, tot = n * pitch;
  for (let i = 0; i <= N; i++) {
    const u = PI2 * n * (i / N), z = -tot / 2 + tot * (i / N), cu = Math.cos(u), su = Math.sin(u);
    for (const [dr, dz] of [[w / 2, h / 2], [-w / 2, h / 2], [-w / 2, -h / 2], [w / 2, -h / 2]]) {
      const r = R + dr;
      pts.push([r * cu, r * su, z + dz]);
    }
  }
  for (let i = 0; i < N; i++) for (let j = 0; j < 4; j++) {
    const k = i * 4 + j;
    faces.push([k, (i + 1) * 4 + j, (i + 1) * 4 + (j + 1) % 4, i * 4 + (j + 1) % 4]);
  }
  faces.push([0, 1, 2, 3]);
  faces.push([N * 4, N * 4 + 3, N * 4 + 2, N * 4 + 1]);
  return mv({ pts, faces });
}
// прямоугольное кольцо-пакет (шихтованный магнитопровод): 4 бруса, зазор между пакетами виден
function sqring(outer, inner, t) {
  const o = outer / 2, i2 = inner / 2, wall = o - i2;
  const a = [];
  for (const s of [1, -1]) {
    a.push(box(outer, wall, t).mv(0, s * (i2 + wall / 2), 0));
    a.push(box(wall, inner, t).mv(s * (i2 + wall / 2), 0, 0));
  }
  return join(a);
}
function box(w, h, d) {
  const x = w / 2, y = h / 2, z = d / 2;
  return mv({
    pts: [-x, -y, -z, x, -y, -z, x, y, -z, -x, y, -z, -x, -y, z, x, -y, z, x, y, z, -x, y, z],
    faces: [[0, 3, 2, 1], [4, 5, 6, 7], [0, 1, 5, 4], [1, 2, 6, 5], [2, 3, 7, 6], [3, 0, 4, 7]]
  });
}
function mv(g) {
  g.mv = (dx, dy, dz) => { for (let i = 0; i < g.pts.length; i += 3) { g.pts[i] += dx; g.pts[i + 1] += dy; g.pts[i + 2] += dz; } return g; };
  return g;
}
function join(arr) {
  const pts = [], faces = [];
  for (const g of arr) { const off = pts.length / 3; pts.push(...g.pts); for (const f of g.faces) faces.push(f.map(i => i + off)); }
  return mv({ pts, faces });
}


// витки катушки: наклонные нити (rot — поворот вокруг касательной к витку)
function turns(Rcoil, z0, pitch, n, nu = 18, rot = 0) {
  const pts = [], faces = [];
  for (let k = 0; k < n; k++) {
    const zc = z0 + k * pitch, ptsK = [];
    for (let i = 0; i < nu; i++) {
      const u = PI2 * i / nu, x = Rcoil * Math.cos(u), y = Rcoil * Math.sin(u);
      const zz = zc + 0.42 * pitch * Math.sin(u);
      if (rot) {
        const rad = [Math.cos(u), Math.sin(u), 0], tan = [-Math.sin(u), Math.cos(u), 0];
        const d = [x, y, zz - zc];
        const perp = [d[0] - rad[0] * d[2], d[1] - rad[1] * d[2], d[2] - rad[2] * d[2]];
        const c = Math.cos(rot), s = Math.sin(rot);
        const pr = perp[0] * rad[0] + perp[1] * rad[1] + perp[2] * rad[2];
        const cr = [perp[1] * rad[2] - perp[2] * rad[1], perp[2] * rad[0] - perp[0] * rad[2], perp[0] * rad[1] - perp[1] * rad[0]];
        const q = [perp[0] * c + cr[0] * s + rad[0] * pr, perp[1] * c + cr[1] * s + rad[1] * pr, perp[2] * c + cr[2] * s + rad[2] * pr];
        ptsK.push([x + q[0], y + q[1], zc + q[2]]);
      } else ptsK.push([x, y, zz]);
    }
    for (let i = 0; i < nu; i++) {
      const a = ptsK[i], c = ptsK[(i + 1) % nu];
      const dx = c[0] - a[0], dy = c[1] - a[1], dz = c[2] - a[2];
      const L = Math.hypot(dx, dy, dz), ux = dx / L, uy = dy / L, uz = dz / L;
      let px = -uz, py = 0, pz = ux;
      const pl = Math.hypot(px, py, pz) || 1; px /= pl; pz /= pl;
      const w = 1.9, t = 0.75;
      const b = pts.length / 3;
      pts.push([a[0] + px * w, a[1] + py * w, a[2] + pz * w], [c[0] + px * w, c[1] + py * w, c[2] + pz * w],
               [c[0] - px * w, c[1] - py * w, c[2] - pz * w], [a[0] - px * w, a[1] - py * w, a[2] - pz * w]);
      faces.push([b, b + 1, b + 2, b + 3]);
      const nx = ux * t, ny = uy * t, nz = uz * t;
      const b2 = pts.length / 3;
      pts.push([a[0] + px * w + nx, a[1] + py * w + ny, a[2] + pz * w + nz], [c[0] + px * w + nx, c[1] + py * w + ny, c[2] + pz * w + nz],
               [c[0] - px * w + nx, c[1] - py * w + ny, c[2] - pz * w + nz], [a[0] - px * w + nx, a[1] - py * w + ny, a[2] - pz * w + nz]);
      faces.push([b2, b2 + 1, b2 + 2, b2 + 3]);
      for (const [q1, q2] of [[[px * w, py * w, pz * w], [px * w + nx, py * w + ny, pz * w + nz]],
                              [[-px * w, -py * w, -pz * w], [-px * w + nx, -py * w + ny, -pz * w + nz]]]) {
        const b3 = pts.length / 3;
        pts.push([a[0] + q1[0], a[1] + q1[1], a[2] + q1[2]], [c[0] + q1[0], c[1] + q1[1], c[2] + q1[2]],
                 [c[0] + q2[0], c[1] + q2[1], c[2] + q2[2]], [a[0] + q2[0], a[1] + q2[1], a[2] + q2[2]]);
        faces.push([b3, b3 + 1, b3 + 2, b3 + 3]);
      }
    }
  }
  return { pts, faces };
}
