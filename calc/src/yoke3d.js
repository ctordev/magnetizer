function autofit(m, cam) {
  const W = 660, H = 420;
  const pts = [];
  for (const part of m.parts) for (let i = 0; i < part.g.pts.length; i += 3)
    pts.push([part.g.pts[i] + (part.t ? part.t[0] : 0), part.g.pts[i + 1] + (part.t ? part.t[1] : 0), part.g.pts[i + 2] + (part.t ? part.t[2] : 0)]);
  const ext = (az, el) => {
    const ca = Math.cos(az * D2R), sa = Math.sin(az * D2R), ce = Math.cos(el * D2R), se = Math.sin(el * D2R);
    let a = [1e9, 1e9, -1e9, -1e9];
    for (const [x, y, z] of pts) {
      const x1 = x * ca - y * sa, y1 = x * sa + y * ca;
      a[0] = Math.min(a[0], x1); a[2] = Math.max(a[2], x1);
      a[1] = Math.min(a[1], -(y1 * se - z * ce)); a[3] = Math.max(a[3], -(y1 * se - z * ce));
    }
    return a;
  };
  // худший по габариту ракурс: полный оборот по азимуту и наклону (вращение теперь 360°)
  let w = 0, h = 0;
  for (let az = 0; az < 360; az += 15) for (const el of [-90, -60, -30, 0, 30, 60, 90]) {
    const a = ext(az, el);
    w = Math.max(w, a[2] - a[0]); h = Math.max(h, a[3] - a[1]);
  }
  cam.fit = 0.74 * Math.min(W / w, H / h);
  const d = ext(cam.az, cam.el);
  cam.ox = -(d[0] + d[2]) / 2 * cam.fit;
  cam.oy = -(d[1] + d[3]) / 2 * cam.fit;
}
