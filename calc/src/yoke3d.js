// ── движок: та же ортографическая проекция и плоское штрихование, что в magnetizer.html,
//    но рисуем в canvas: 3–8 тыс. полигонов как SVG пересобираются в DOM каждый кадр и тормозят ──
function fxEngine() {
  const W = 660, H = 420;
  const wrap = (s, n = 38) => {
    const out = []; let cur = '';
    for (const word of String(s).split(' ')) {
      if ((cur + ' ' + word).trim().length > n) { out.push(cur.trim()); cur = word; }
      else cur += ' ' + word;
    }
    if (cur.trim()) out.push(cur.trim());
    return out;
  };
  function fxProject(sc) {
    const cam = sc.cam, k = cam.k || 1, fit = cam.fit * k, ox = cam.ox * k, oy = cam.oy * k;
    const ca = Math.cos(cam.az * D2R), sa = Math.sin(cam.az * D2R);
    const ce = Math.cos(cam.el * D2R), se = Math.sin(cam.el * D2R);
    const px = (x, y, z) => W / 2 + ox + (x * ca - y * sa) * fit;
    const py = (x, y, z) => H / 2 + oy - ((x * sa + y * ca) * se - z * ce) * fit;
    const pz = (x, y, z) => (x * sa + y * ca) * ce + z * se;
    const faces = [];
    for (const part of sc.parts) {
      const g = part.g, F = g.faces, col = part.m || '#8e99a8', op = part.op == null ? .93 : part.op;
      if (!part.wp) {
        const src = g.pts, tx = part.t ? part.t[0] : 0, ty = part.t ? part.t[1] : 0, tz = part.t ? part.t[2] : 0;
        const a = new Float64Array(src.length);
        for (let i = 0; i < src.length; i += 3) { a[i] = src[i] + tx; a[i + 1] = src[i + 1] + ty; a[i + 2] = src[i + 2] + tz; }
        part.wp = a;
      }
      const src = part.wp;
      for (let f = 0; f < F.length; f++) {
        const q = F[f], n = q.length;
        const x0 = src[q[0] * 3], y0 = src[q[0] * 3 + 1], z0 = src[q[0] * 3 + 2];
        const ux = src[q[1] * 3] - x0, uy = src[q[1] * 3 + 1] - y0, uz = src[q[1] * 3 + 2] - z0;
        const vx = src[q[2] * 3] - x0, vy = src[q[2] * 3 + 1] - y0, vz = src[q[2] * 3 + 2] - z0;
        const nz = ux * vy - uy * vx;
        const nx = uy * vz - uz * vy, ny = uz * vx - ux * vz;
        const ln = Math.sqrt(nx * nx + ny * ny + nz * nz) || 1;
        let area = 0, zz = 0;
        const sx = [], sy = [];
        for (let i = 0; i < n; i++) {
          const o = q[i] * 3, X = src[o], Y = src[o + 1], Z = src[o + 2];
          const pxv = W / 2 + ox + (X * ca - Y * sa) * fit, pyv = H / 2 + oy - ((X * sa + Y * ca) * se - Z * ce) * fit;
          sx.push(pxv); sy.push(pyv); zz += (X * sa + Y * ca) * ce + Z * se;
        }
        const p = new Array(n * 2);
        for (let i = 0; i < n; i++) {
          const j = (i + 1) % n;
          area += sx[i] * sy[j] - sx[j] * sy[i];
          p[i * 2] = sx[i]; p[i * 2 + 1] = sy[i];
        }
        if (area <= 0) continue;
        const lz = Math.max(.25, Math.min(1.05, .58 - (nz / ln) * .42));
        faces.push({ z: zz / n, p, c: col, a: op * lz });
      }
    }
    faces.sort((u, v) => u.z - v.z);
    const items = [];
    if (sc.labels !== false) for (const p of sc.parts) {
      if (!p.lbl || !p.lp) continue;
      const ax = px(p.lp[0], p.lp[1], p.lp[2]), ay = py(p.lp[0], p.lp[1], p.lp[2]);
      items.push({ a: [ax, ay], lines: wrap(p.lbl), right: ax > W / 2, col: p.ly || '#9fb0c8' });
    }
    const labels = [];
    for (const right of [false, true]) {
      let ey = 20;
      for (const it of items.filter(i => i.right === right).sort((u, v) => u.a[1] - v.a[1])) {
        if (ey > H - 14) break;
        const ex = right ? W - 8 : 8;
        labels.push({ a: it.a, lines: it.lines, col: it.col, ex, ey, right });
        ey += 14 * it.lines.length + 8;
      }
    }
    return { faces, labels };
  }
  function fxPaint(cv, sc) {
    const dpr = Math.min(2, window.devicePixelRatio || 1);
    if (cv.width !== Math.round(W * dpr)) { cv.width = Math.round(W * dpr); cv.height = Math.round(H * dpr); }
    const g = cv.getContext('2d');
    g.setTransform(dpr, 0, 0, dpr, 0, 0);
    g.fillStyle = '#161a20'; g.fillRect(0, 0, W, H);
    const r = fxProject(sc);
    let bc = null, ba = -1;
    g.beginPath();
    for (const f of r.faces) {
      if (f.a >= .99 && f.c === bc && f.a === ba) {
        g.moveTo(f.p[0], f.p[1]);
        for (let i = 2; i < f.p.length; i += 2) g.lineTo(f.p[i], f.p[i + 1]);
        g.closePath();
        continue;
      }
      if (bc !== null) { g.globalAlpha = ba; g.fillStyle = bc; g.fill(); g.beginPath(); }
      bc = f.c; ba = f.a;
      g.moveTo(f.p[0], f.p[1]);
      for (let i = 2; i < f.p.length; i += 2) g.lineTo(f.p[i], f.p[i + 1]);
      g.closePath();
    }
    if (bc !== null) { g.globalAlpha = ba; g.fillStyle = bc; g.fill(); }
    for (const f of r.faces) if (f.a < .99) {
      g.beginPath(); g.moveTo(f.p[0], f.p[1]);
      for (let i = 2; i < f.p.length; i += 2) g.lineTo(f.p[i], f.p[i + 1]);
      g.closePath(); g.globalAlpha = f.a; g.fillStyle = f.c; g.fill();
    }
    g.globalAlpha = 1;
    g.lineWidth = 1;
    for (const L of r.labels) {
      g.strokeStyle = L.col;
      g.beginPath(); g.moveTo(L.a[0], L.a[1]); g.lineTo(L.ex + (L.right ? -12 : 12), L.ey - 4); g.stroke();
      g.beginPath(); g.arc(L.a[0], L.a[1], 2.6, 0, 6.284); g.fillStyle = L.col; g.fill();
    }
    g.font = '10.5px system-ui,"Segoe UI",Roboto,sans-serif';
    g.lineJoin = 'round'; g.lineWidth = 3.2; g.strokeStyle = '#12161c';
    for (const L of r.labels) {
      g.textAlign = L.right ? 'right' : 'left';
      let ty = L.ey;
      for (const ln of L.lines) { g.strokeText(ln, L.ex, ty); ty += 14; }
      g.fillStyle = L.col; ty = L.ey;
      for (const ln of L.lines) { g.fillText(ln, L.ex, ty); ty += 14; }
    }
  }
  function fxSVG(sc) {
    const r = fxProject(sc);
    let s = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}"><rect width="${W}" height="${H}" fill="#161a20"/>`;
    for (const f of r.faces)
      s += `<polygon points="${f.p.map(v => v.toFixed(1)).join(' ')}" fill="${f.c}" fill-opacity="${f.a.toFixed(2)}"/>`;
    for (const L of r.labels) {
      s += `<polyline points="${L.a.map(v => v.toFixed(1)).join(',')} ${L.ex + (L.right ? -12 : 12)},${L.ey - 4}" fill="none" stroke="${L.col}"/>`;
      let ty = L.ey;
      for (const ln of L.lines) { s += `<text x="${L.ex}" y="${ty}" text-anchor="${L.right ? 'end' : 'start'}" font-size="10.5" fill="${L.col}">${ln}</text>`; ty += 14; }
    }
    return s + '</svg>';
  }
  function fxView(host, sc, def) {
    const cv = document.createElement('canvas');
    cv.className = 'fx3d'; cv.width = W; cv.height = H;
    host.appendChild(cv);
    let raf = 0;
    const draw = () => { raf = 0; fxPaint(cv, sc); };
    const need = () => { if (!raf) raf = requestAnimationFrame(draw); };
    let drag = null;
    cv.addEventListener('pointerdown', e => { drag = { x: e.clientX, y: e.clientY }; try { cv.setPointerCapture(e.pointerId); } catch (e) {} });
    cv.addEventListener('pointermove', e => {
      if (!drag) return;
      // «схватил и тяну»: ближняя к камере грань идёт за курсором; вращение полное, 360°
      sc.cam.az -= (e.clientX - drag.x) * .5;
      let el = sc.cam.el - (e.clientY - drag.y) * .35;
      while (el > 90) { el = 180 - el; sc.cam.az += 180; }        // через верхний полюс
      while (el < -90) { el = -180 - el; sc.cam.az += 180; }      // через нижний
      sc.cam.el = el;
      sc.cam.az = ((sc.cam.az + 180) % 360) - 180;
      drag = { x: e.clientX, y: e.clientY }; need();
    });
    ['pointerup', 'pointercancel', 'pointerleave'].forEach(t => cv.addEventListener(t, () => { drag = null; }));
    cv.addEventListener('wheel', e => { e.preventDefault(); sc.cam.k = Math.max(.35, Math.min(4, (sc.cam.k || 1) * (e.deltaY < 0 ? 1.08 : .925))); need(); }, { passive: false });
    draw();
    return { need, reset() { sc.cam.az = def.az; sc.cam.el = def.el; sc.cam.k = 1; need(); }, dump: () => fxSVG(sc) };
  }
  return { fxPaint, fxSVG, fxView };
}

