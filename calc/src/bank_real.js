// Реальный состав банка (§3.2): 10 × EPCOS B43560-S9478-M1 (4700 мкФ/400 В, все б/у, приёмка каждой).
// Резерв «boost» — 10×2800 + 5×3200 (не подключены; ESL/ESR там — допущения, мерять). 2×5800 в банк не идут:
// в любом миксе по Z=√(ESL/C) они забирают больше всех банок и это наименее документированные банки.
// Режим разряда считает rlc.js — та же модель, что в master.js; здесь только составы и прогон для таблицы.
// Пуск: node calc/src/bank_real.js
const EM = require('./em.js');
const { sim, splitParts, T253, VL200, Rs } = require('./rlc.js');

const N = 24, L = EM.FIX.L;
const RCONT = 0.0085 + 0.0035;    // обмотка оснастки (25 мм²) + шины/тиристор; ESR банка — Rs в rlc.js
const P47 = [4700, 10, 30];       // ESL однотипному банку не нужен (деление I/n), но состав храним в общем формате
const VAR = [
  ['10×4700 — принято', 47.0e-3, [P47]],
  ['11×4700 — если найдётся ещё', 51.7e-3, [[4700, 11, 30]]],
  ['8×4700 — минимальный состав', 37.6e-3, [[4700, 8, 30]]],
  ['5×4700 — что есть сегодня', 23.5e-3, [[4700, 5, 30]]],
  ['10×4700 + 5×3200 — boost', 63.0e-3, [P47, [3200, 5, 17]]],
  ['10×4700 + 10×2800 + 5×3200 — весь резерв', 91.0e-3, [P47, [2800, 10, 18], [3200, 5, 17]]],
];

const f = (x, d = 1, u = 1) => (x / u).toLocaleString('ru-RU', { maximumFractionDigits: d, minimumFractionDigits: d });

for (const U0 of [300, 320, 350]) {
  console.log(`\n================ U = ${U0} В ================`);
  for (const [name, C, parts] of VAR) {
    const r = sim(C, U0, L, RCONT, N);
    const sp = splitParts(r.ipk, parts);
    console.log(`\n${name}: C=${f(C * 1e3, 1)} мкФ  E=${f(r.E / 1000, 2)} кДж  Q=${f(r.Q, 1)} Кл  T/2=${f(r.Thalf * 1e3, 1)} мс`);
    console.log(`  I_pk=${f(r.ipk / 1000, 2)} кА  N·I=${f(N * r.ipk / 1000, 0)} кА·вит  коммутация ${f(r.tc * 1000, 2)} мс`);
    console.log(`  i²t VD6=${f(r.i2tD / 1e3, 0)} кА²с → 1 диод при 2×ВЛ200 ${f(r.i2tD / 2 / VL200.i2t * 100, 0)}%, при 3× ${f(r.i2tD / 3 / VL200.i2t * 100, 0)}%`);
    console.log(`  VT1: i²t ${f(r.i2tS / T253.i2t * 100, 1)}% паспорта, пик ${f(r.ipkS / T253.itsm * 100, 0)}% Itsm`);
    console.log('  ток на банку: ' + sp.map(s => `${s.uf}мкФ×${s.n} → ${f(s.I, 0)} А`).join('; ') +
      ` (всего банок ${parts.reduce((s, p) => s + p[1], 0)})`);
    console.log(`  нагрев обмотки ${f(0.9 * r.E / (3.2 * 385), 1)} °C за выстрел; U банок = ${f(U0 / 400 * 100, 0)}% паспорта`);
  }
}

// ── чувствительность к деградации б/у: растёт только ESR (Rs), ёмкость считаем целой ──────────────
console.log('\n================ 10×4700, 300 В — б/у ESR вместо 40 мОм/шт ================');
for (const esrOf of [40, 80, 120]) {
  const r = sim(47.0e-3, 300, L, RCONT + (esrOf * 1e-3) / 10 - Rs, N);
  console.log(`ESR=${esrOf} мОм/шт: I_pk=${f(r.ipk / 1000, 2)} кА  N·I=${f(N * r.ipk / 1000, 0)} кА·вит  ` +
    `i²t VD6 ${(f(r.i2tD / 2 / VL200.i2t * 100, 0))}% на диод  на банку ${f(r.ipk / 10, 0)} А`);
}
console.log('Приёмка каждой банки до установки: C (допуск −20%), ESR (паспорт ≤40 мОм; б/у до ~80 мОм рабочие), клапан/течь.');
